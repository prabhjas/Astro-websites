#!/usr/bin/env bash
# Proves SHA-before-execution, sealed execution, effective systemd inventory,
# exact SITE rows, missing-marker/symlink rejection, atomic install and rollback.

set -euo pipefail
IFS=$'\n\t'

SCRIPT_DIR=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd -P)
CANDIDATE=$SCRIPT_DIR/templates/restic-astro-fleet-backup.sh
WRAPPER=$SCRIPT_DIR/06-restic-fleet-coverage.sh
TMP_ROOT=$(mktemp -d /tmp/astro-restic-fixture.XXXXXX)
cleanup() {
  case "$TMP_ROOT" in /tmp/astro-restic-fixture.*) rm -rf -- "$TMP_ROOT" ;; esac
}
trap cleanup EXIT

FLEET=$TMP_ROOT/Astro-production
REPOSITORY=$TMP_ROOT/restic-repository
PASSWORD_FILE=$TMP_ROOT/restic.password
BIN=$TMP_ROOT/bin
MANIFEST=$TMP_ROOT/active-sites.tsv
mkdir -p -- "$REPOSITORY" "$BIN"
chmod 0700 -- "$REPOSITORY" "$BIN"
printf 'fixture-restic-config\n' >"$REPOSITORY/config"
printf 'fixture-password-not-real\n' >"$PASSWORD_FILE"
chmod 0600 -- "$REPOSITORY/config" "$PASSWORD_FILE"

# The production reviewed map is 29 exact unit/site identities (28 CMS sites
# plus the active non-CMS connectresourcesint service), not merely a count.
bash "$CANDIDATE" --print-expected-sites >"$TMP_ROOT/reviewed-site-map.tsv"
[[ "$(wc -l <"$TMP_ROOT/reviewed-site-map.tsv")" == 29 ]] || exit 1
grep -Fqx $'SITE\tconnectresourcesint.service\tconnectresourcesint.com' \
  "$TMP_ROOT/reviewed-site-map.tsv" || exit 1
[[ -z "$(cut -f2 "$TMP_ROOT/reviewed-site-map.tsv" | sort | uniq -d)" ]] || exit 1
[[ -z "$(cut -f3 "$TMP_ROOT/reviewed-site-map.tsv" | sort | uniq -d)" ]] || exit 1

for site in one.test two.test three.test four.test five.test; do
  mkdir -p -- "$FLEET/$site/.data/leads" "$FLEET/$site/.data/internal-admin"
  printf '{}\n' >"$FLEET/$site/package.json"
  printf 'LEAD_STORE_DIR=.data/leads\nINTERNAL_ADMIN_DIR=.data/internal-admin\n' >"$FLEET/$site/.env.prod"
done
mkdir -p -- "$FLEET/one.test/.data/from-production-env"
printf 'INTERNAL_UPLOAD_DIR=.data/from-production-env\n' >"$FLEET/one.test/.env.production"

cat >"$BIN/systemctl" <<'SYSTEMCTL'
#!/usr/bin/env bash
set -euo pipefail
unit=${2:-}
case "${1:-}" in
  list-units)
    printf '%s loaded active running fixture\n' \
      site-one.service site-two.service site-three.service site-four.service site-five.service
    [[ "${INCLUDE_MISSING:-0}" != 1 ]] || printf 'site-missing.service loaded active running fixture\n'
    ;;
  show)
    if [[ "$*" == *'WorkingDirectory'* ]]; then
      case "$unit" in
        site-one.service) printf '%s/one.test\n' "$FIXTURE_FLEET" ;;
        site-two.service) printf '%s/two.test\n' "$FIXTURE_FLEET" ;;
        site-three.service) printf '%s/three.test\n' "$FIXTURE_FLEET" ;;
        site-four.service) printf '%s/four.test\n' "$FIXTURE_FLEET" ;;
        site-five.service) printf '%s/five.test\n' "$FIXTURE_FLEET" ;;
        site-missing.service) printf '%s/missing.test\n' "$FIXTURE_FLEET" ;;
        *) exit 64 ;;
      esac
    elif [[ "$*" == *'LoadState'* ]]; then
      printf 'loaded\n'
    else
      exit 64
    fi
    ;;
  is-active)
    unit=${!#}
    case "$unit" in
      restic-astro-fleet.service|restic-astro-fleet.timer) exit 3 ;;
      site-*.service) exit 0 ;;
      *) exit 4 ;;
    esac
    ;;
  *) exit 64 ;;
esac
SYSTEMCTL
chmod 0755 -- "$BIN/systemctl"
export FIXTURE_FLEET=$FLEET

{
  printf 'SITE\tsite-five.service\tfive.test\t%s/five.test\n' "$FLEET"
  printf 'SITE\tsite-four.service\tfour.test\t%s/four.test\n' "$FLEET"
  printf 'SITE\tsite-one.service\tone.test\t%s/one.test\n' "$FLEET"
  printf 'SITE\tsite-three.service\tthree.test\t%s/three.test\n' "$FLEET"
  printf 'SITE\tsite-two.service\ttwo.test\t%s/two.test\n' "$FLEET"
} | sort >"$MANIFEST"
chown 0:0 -- "$MANIFEST"
chmod 0600 -- "$MANIFEST"

output=$TMP_ROOT/coverage.txt
SITE_ROOT=$FLEET ACTIVE_SITE_MANIFEST=$MANIFEST EXPECTED_ACTIVE_SITES=5 \
  ALLOW_NONSTANDARD_SITE_MAP=1 EXPECTED_SITE_MAP=$MANIFEST \
  bash "$CANDIDATE" --dry-run >"$output"
[[ "$(awk -F '\t' '$1 == "SITES" {print $2}' "$output")" == 5 ]] || exit 1
for site in one.test two.test three.test four.test five.test; do
  grep -Fqx $'SITE\t'"$site"$'\t'"$FLEET/$site" "$output" || exit 1
done
grep -Fqx $'PATH\t'"$FLEET/one.test/.env.production" "$output" || exit 1
grep -Fqx $'PATH\t'"$FLEET/one.test/.data/from-production-env" "$output" || exit 1

# Scheduled invocation has no durable external manifest. It must regenerate and
# revalidate the effective active inventory on every run.
SITE_ROOT=$FLEET EXPECTED_ACTIVE_SITES=5 ASTRO_SYSTEMCTL=$BIN/systemctl \
  ALLOW_NONSTANDARD_SITE_MAP=1 EXPECTED_SITE_MAP=$MANIFEST \
  bash "$CANDIDATE" --dry-run >"$TMP_ROOT/autogenerated.txt"
cmp -s -- "$output" "$TMP_ROOT/autogenerated.txt" || exit 1

candidate_sha=$(sha256sum "$CANDIDATE" | awk '{print $1}')
installed=$TMP_ROOT/installed-restic
cp -- "$CANDIDATE" "$installed"
chmod 0755 -- "$installed"

# A digest is mandatory before any candidate execution, and nonstandard targets
# and site counts each need their explicit fixture gate.
if ASTRO_SYSTEMCTL=$BIN/systemctl bash "$WRAPPER" --root "$FLEET" \
  --candidate "$CANDIDATE" --installed "$installed" --repository "$REPOSITORY" \
  --password-file "$PASSWORD_FILE" >"$TMP_ROOT/no-digest.out" 2>&1; then
  printf 'Candidate was accepted without a reviewed digest\n' >&2; exit 1
fi
if ASTRO_SYSTEMCTL=$BIN/systemctl bash "$WRAPPER" --root "$FLEET" \
  --candidate "$CANDIDATE" --reviewed-candidate-sha256 "$candidate_sha" \
  --installed "$installed" --repository "$REPOSITORY" --password-file "$PASSWORD_FILE" \
  --expected-active-sites 5 --allow-nonstandard-site-count >"$TMP_ROOT/no-target-gate.out" 2>&1; then
  printf 'Nonstandard install target was accepted without its gate\n' >&2; exit 1
fi

ASTRO_SYSTEMCTL=$BIN/systemctl bash "$WRAPPER" --root "$FLEET" \
  --candidate "$CANDIDATE" --reviewed-candidate-sha256 "$candidate_sha" \
  --installed "$installed" --allow-nonstandard-install-target \
  --expected-active-sites 5 --allow-nonstandard-site-count \
  --repository "$REPOSITORY" --password-file "$PASSWORD_FILE" >/dev/null

# Atomic new-target install and exact-hash rollback removal. No service starts.
atomic_target=$BIN/restic-fleet-fixture
atomic_backup=$TMP_ROOT/atomic-rollback
ASTRO_SYSTEMCTL=$BIN/systemctl bash "$WRAPPER" --apply --root "$FLEET" \
  --candidate "$CANDIDATE" --reviewed-candidate-sha256 "$candidate_sha" \
  --installed "$atomic_target" --allow-nonstandard-install-target \
  --expected-active-sites 5 --allow-nonstandard-site-count \
  --repository "$REPOSITORY" --password-file "$PASSWORD_FILE" \
  --backup-dir "$atomic_backup" >/dev/null
[[ "$(stat -c '%u:%g:%a' "$atomic_target")" == 0:0:755 ]] || exit 1
[[ "$(sha256sum "$atomic_target" | awk '{print $1}')" == "$candidate_sha" ]] || exit 1
[[ "$(<"$atomic_backup/.astro-restic-script-backup")" == astro-security-remediation-20260809 ]] || exit 1
ASTRO_SYSTEMCTL=$BIN/systemctl bash "$atomic_backup/rollback-restic-script.sh" >/dev/null
[[ ! -e "$atomic_target" ]] || { printf 'Rollback did not remove newly installed target\n' >&2; exit 1; }

# An active WorkingDirectory with no marker is visible and blocks; it is never
# omitted by candidate glob heuristics.
mkdir -p -- "$FLEET/missing.test"
if INCLUDE_MISSING=1 ASTRO_SYSTEMCTL=$BIN/systemctl bash "$WRAPPER" --root "$FLEET" \
  --candidate "$CANDIDATE" --reviewed-candidate-sha256 "$candidate_sha" \
  --installed "$installed" --allow-nonstandard-install-target \
  --expected-active-sites 6 --allow-nonstandard-site-count \
  --repository "$REPOSITORY" --password-file "$PASSWORD_FILE" >"$TMP_ROOT/missing.out" 2>&1; then
  printf 'Active missing-marker site was silently omitted\n' >&2; exit 1
fi
grep -q 'no reviewed runtime marker' "$TMP_ROOT/missing.out" || exit 1

# Runtime escapes and symlinked stores both fail without echoing the value.
printf 'LEAD_STORE_DIR=../../etc\n' >"$FLEET/five.test/.env.prod"
if SITE_ROOT=$FLEET ACTIVE_SITE_MANIFEST=$MANIFEST EXPECTED_ACTIVE_SITES=5 \
  ALLOW_NONSTANDARD_SITE_MAP=1 EXPECTED_SITE_MAP=$MANIFEST \
  bash "$CANDIDATE" --dry-run >"$TMP_ROOT/unsafe.out" 2>"$TMP_ROOT/unsafe.err"; then
  printf 'Unsafe runtime path was accepted\n' >&2; exit 1
fi
grep -q 'value suppressed' "$TMP_ROOT/unsafe.err" || exit 1
if grep -q '/etc' "$TMP_ROOT/unsafe.err"; then printf 'Unsafe value leaked in error\n' >&2; exit 1; fi
printf 'LEAD_STORE_DIR=.data/leads\n' >"$FLEET/five.test/.env.prod"
for unsafe_external in /var/backups/astro-fleet /var/lib; do
  printf 'LEAD_STORE_DIR=%s\n' "$unsafe_external" >"$FLEET/five.test/.env.prod"
  if SITE_ROOT=$FLEET ACTIVE_SITE_MANIFEST=$MANIFEST EXPECTED_ACTIVE_SITES=5 \
    ALLOW_NONSTANDARD_SITE_MAP=1 EXPECTED_SITE_MAP=$MANIFEST \
    bash "$CANDIDATE" --dry-run >"$TMP_ROOT/broad-root.out" 2>"$TMP_ROOT/broad-root.err"; then
    printf 'Broad/excluded external runtime path was accepted\n' >&2
    exit 1
  fi
  grep -q 'value suppressed' "$TMP_ROOT/broad-root.err" || exit 1
  if grep -Fq -- "$unsafe_external" "$TMP_ROOT/broad-root.err"; then
    printf 'Rejected external runtime value leaked in error\n' >&2
    exit 1
  fi
done
printf 'LEAD_STORE_DIR=.data/leads\n' >"$FLEET/five.test/.env.prod"
if RESTIC_REPOSITORY="$FLEET/five.test/.data/leads" SITE_ROOT=$FLEET \
  ACTIVE_SITE_MANIFEST=$MANIFEST EXPECTED_ACTIVE_SITES=5 \
  ALLOW_NONSTANDARD_SITE_MAP=1 EXPECTED_SITE_MAP=$MANIFEST \
  bash "$CANDIDATE" --dry-run >/dev/null 2>"$TMP_ROOT/repository-overlap.err"; then
  printf 'Runtime path overlapping the Restic repository was accepted\n' >&2
  exit 1
fi
grep -q 'value suppressed' "$TMP_ROOT/repository-overlap.err" || exit 1
if RESTIC_CACHE_DIR="$FLEET/five.test/.data/leads/cache" SITE_ROOT=$FLEET \
  ACTIVE_SITE_MANIFEST=$MANIFEST EXPECTED_ACTIVE_SITES=5 \
  ALLOW_NONSTANDARD_SITE_MAP=1 EXPECTED_SITE_MAP=$MANIFEST \
  bash "$CANDIDATE" --dry-run >/dev/null 2>"$TMP_ROOT/cache-overlap.err"; then
  printf 'Runtime path containing the Restic cache was accepted\n' >&2
  exit 1
fi
grep -q 'value suppressed' "$TMP_ROOT/cache-overlap.err" || exit 1
mv "$FLEET/four.test/.data" "$FLEET/four.test/.data.real"
ln -s .data.real "$FLEET/four.test/.data"
if SITE_ROOT=$FLEET ACTIVE_SITE_MANIFEST=$MANIFEST EXPECTED_ACTIVE_SITES=5 \
  ALLOW_NONSTANDARD_SITE_MAP=1 EXPECTED_SITE_MAP=$MANIFEST \
  bash "$CANDIDATE" --dry-run >/dev/null 2>"$TMP_ROOT/symlink.err"; then
  printf 'Symlinked runtime store was accepted\n' >&2; exit 1
fi
grep -q 'unsafe marker' "$TMP_ROOT/symlink.err" || exit 1

printf 'PASS: sealed bytes, exact active SITE rows, contained/allowlisted runtime paths, scheduled revalidation, and atomic rollback\n'
